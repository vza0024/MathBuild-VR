@pytest.mark.parametrize("reply", [
    "There are two apples left in the basket.",
    "The answer is two.",
    "You have two cookies left.",
])
def test_small_word_equal_to_answer_still_blocked(reply):
    # REMOVE question whose answer is 2: "two" must still be caught.
    question = next(q for q in QUESTION_BY_ID.values() if q["interaction"] == "REMOVE"
                    and q["unknown_position"] == "RESULT" and q["parameters"]["result"] == 2)
    p = question["parameters"]
    args = build(question["id"], {"removed_count": 0, "remaining_count": p["initial"]})
    assert rule(reply, *args) is not None


def test_digits_are_never_exempt():
    args = build(JOIN_ID, JOIN_STATE)
    assert rule("Move 1 more apple and then 5 more into the basket.", *args) is not None
    assert rule("Look at 5 apples in the basket.", *args) == "number_not_allowed"


def test_one_step_check_is_not_stricter_than_v4():
    # "shares" must not count as a second action (v4 verdict: safe).
    question = next(q for q in QUESTION_BY_ID.values() if q["interaction"] == "EQUAL_SHARING")
    n = question["parameters"]["recipient_count"]
    args = build(question["id"], {"share_sizes": [1] + [0] * (n - 1),
                                  "undistributed_count": question["parameters"]["total"] - 1})
    plan_text = args[3]["correction_plan"]["safe_next_step"]
    assert rule(plan_text, *args) is None, plan_text


# --- Restricted Fix B: which "one"/"two" stay counted ----------------------------

@pytest.mark.parametrize("reply", [
    "Move two more apples into the basket.",          # exact move: verb + number
    "Put one more apple in the basket.",              # "one more"
    "Look at the basket: it should have one apple.",  # names the object
    "Look at the two apples in the basket.",          # names the object
    "Give one cinnamon swirl to each person.",        # move verb before the number
])
def test_small_words_that_are_quantities_stay_counted(reply):
    from app.answer_protection import quantity_numbers

    question = QUESTION_BY_ID["MC-JOIN-nluds-0001"]
    question = {**question, "visual": {**question["visual"], "object_label": "apple",
                                       "object_plural": "apples"}}
    if "cinnamon" in reply:
        question = next(q for q in QUESTION_BY_ID.values() if q["interaction"] == "EQUAL_SHARING"
                        and "cinnamon" in q["body"])
    numbers = quantity_numbers(reply, 999, question)
    assert numbers & {1, 2}, reply


@pytest.mark.parametrize("reply, question_type", [
    ("It means all the red apples and green apples, not just one color.", "JOIN"),
    ("The story is about all the cousins, not just to one cousin.", "EQUAL_GROUPS"),
    ("A ratio tells how the two groups compare.", "PART_TO_PART_RATIO"),
])
def test_small_words_that_are_ordinary_words_are_not_counted(reply, question_type):
    from app.answer_protection import quantity_numbers

    question = next(q for q in QUESTION_BY_ID.values() if q["interaction"] == question_type
                    and q["parameters"].get("result", 0) not in (1, 2))
    assert not quantity_numbers(reply, 999, question) & {1, 2}, reply


def test_two_groups_is_counted_in_an_equal_groups_story():
    # In EQUAL_GROUPS "two groups" is a count of groups, not the story's two parts.
    from app.answer_protection import quantity_numbers

    question = next(q for q in QUESTION_BY_ID.values() if q["interaction"] == "EQUAL_GROUPS")
    assert 2 in quantity_numbers("Look at the two groups.", 999, question)
