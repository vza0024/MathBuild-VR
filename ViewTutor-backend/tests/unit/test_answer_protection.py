"""Answer protection: parity with v4 and one regression test per rule.

`v4_protection_verdicts.json` holds 6,740 (request, reply) pairs with the verdict
v4's own `response_is_safe` gave. It was generated by running v4's code. With
identical inputs the port agrees on all of them; the only differences in the
full pipeline come from the deliberate two-part JOIN planning change.
"""
from __future__ import annotations

import json

import pytest

from app.answer_protection import check_response, number_values, response_is_safe
from app.evaluator import evaluate
from app.questions import QUESTION_BY_ID
from app.schemas import TutorRequest
from app.strategies import strategy_context
from app.validation import validate_workspace
from tests.conftest import FIXTURES


def build(question_id: str, state: dict, support_type: str = "HINT", message: str = "", history=None):
    question = QUESTION_BY_ID[question_id]
    request = TutorRequest(question_id=question_id, learner_state=state, support_type=support_type,
                           student_message=message, conversation_history=history or [])
    evaluation = evaluate(question, validate_workspace(question, state).workspace)
    facts = dict(evaluation.facts)
    return question, request, facts, strategy_context(question, facts, support_type)


def rule(reply: str, *args) -> str | None:
    return check_response(reply, *args)


# --- Parity with v4 -------------------------------------------------------------

@pytest.fixture(scope="module")
def verdicts():
    return json.loads((FIXTURES / "v4_protection_verdicts.json").read_text(encoding="utf-8"))


def test_parity_with_v4(verdicts):
    """The port is never stricter than v4, and every relaxation is safe.

    Differences come only from deliberate changes: the two-part JOIN plan,
    hint inflections and the small-word rule. None of the replies
    that v4 blocked and the port accepts contains the hidden answer.
    """
    from app.answer_protection import number_values
    from app.evaluator import hidden_answer

    assert len(verdicts) == 6740
    stricter, relaxed = [], []
    for case in verdicts:
        question = QUESTION_BY_ID[case["question_id"]]
        request = TutorRequest.model_validate(case["request"])
        evaluation = evaluate(question, validate_workspace(question, case["learner_state"]).workspace)
        facts = dict(evaluation.facts)
        context = strategy_context(question, facts, request.support_type)
        ours = check_response(case["reply"], question, request, facts, context) is None
        if ours == case["v4_safe"]:
            continue
        (relaxed if ours else stricter).append((question, request, case["reply"]))
    assert stricter == []
    for question, request, reply in relaxed:
        assert hidden_answer(question) not in number_values(reply), reply
        assert request.support_type in {"HINT", "SIMPLIFY_STORY"}
    assert len(relaxed) <= 50


# --- One test per rule -----------------------------------------------------------

JOIN_ID = "MC-JOIN-nluds-0001"                       # 7 red + 2 green apples, answer 9
JOIN_STATE = {"added_count": 1, "current_count": 8}  # incomplete


def test_safe_hint_passes():
    args = build(JOIN_ID, JOIN_STATE)
    assert rule("Move 1 more apple from the object bank into the basket.", *args) is None


@pytest.mark.parametrize("reply, expected", [
    ("", "length"),
    ("x" * 600, "length"),
    ("My confidence is high that the apples are fine.", "internal_terms"),
    ("Ask the student to count the apples.", "third_party_instruction"),
    ("The answer is near. Count the apples.", "answer_phrase"),
    ("There are 9 apples in the basket.", "hidden_answer_disclosure"),
    ("You will have nine apples.", "hidden_answer_disclosure"),
    ("Move 5 apples into the basket.", "number_not_allowed"),
])
def test_general_rules(reply, expected):
    assert rule(reply, *build(JOIN_ID, JOIN_STATE)) == expected


def test_answer_as_quantity():
    # 9 is the answer; pairing it with the objects asserts how many there are.
    assert rule("Look at the basket: 9 apples are left after moving.", *build(JOIN_ID, JOIN_STATE)) in {
        "hidden_answer_disclosure", "number_not_allowed", "answer_as_quantity"}


def test_correct_confirmation_must_not_contain_numbers():
    args = build(JOIN_ID, {"added_count": 2, "current_count": 9})
    assert rule("Great, 2 green apples joined. Nice work.", *args) == "number_in_confirmation"
    assert rule("The arrangement now matches the change described in the story. Well done.", *args) is None


def test_invents_learner_answer():
    assert rule("You wrote a number in the box; look at the apples.", *build(JOIN_ID, JOIN_STATE)) == \
        "invents_learner_answer"


def test_contradicts_story():
    assert rule("You do not need two green apples in the basket.", *build(JOIN_ID, JOIN_STATE)) == \
        "contradicts_story"


def test_hint_needs_an_action_and_one_step():
    args = build(JOIN_ID, JOIN_STATE)
    assert rule("Apples are nice in a basket.", *args) == "hint_no_action"
    assert rule("First move an apple, then count the apples in the basket.", *args) == "hint_multiple_steps"


def test_hint_must_be_grounded():
    assert rule("Try to count slowly.", *build(JOIN_ID, JOIN_STATE)) == "hint_not_grounded"


def _sharing():
    question = next(q for q in QUESTION_BY_ID.values() if q["interaction"] == "EQUAL_SHARING")
    n = question["parameters"]["recipient_count"]
    state = {"share_sizes": [0] * n, "undistributed_count": question["parameters"]["total"]}
    return question, state


def test_hint_sharing_operation_blocked():
    question, state = _sharing()
    p = question["parameters"]
    reply = f"Divide {p['total']} by {p['recipient_count']} to share them."
    assert rule(reply, *build(question["id"], state)) == "hint_sharing_operation"


def test_hint_groups_operation_blocked():
    question = next(q for q in QUESTION_BY_ID.values() if q["interaction"] == "EQUAL_GROUPS")
    p = question["parameters"]
    state = {"group_sizes": [], "undistributed_count": p["total"]}
    reply = f"Multiply {p['group_count']} by {p['group_size']} groups."
    assert rule(reply, *build(question["id"], state)) == "hint_groups_operation"


def test_check_work_must_inspect_not_correct():
    args = build(JOIN_ID, JOIN_STATE, support_type="CHECK_WORK")
    assert rule("Move 1 more apple into the basket.", *args) == "check_not_inspection"
    assert rule("Compare the apples in your basket with the story. What do you notice?", *args) is None


def test_check_work_must_be_grounded():
    assert rule("What do you notice?", *build(JOIN_ID, JOIN_STATE, support_type="CHECK_WORK")) == \
        "check_not_grounded"


def test_story_help_must_be_about_the_story():
    assert rule("Nice try, keep going.", *build(JOIN_ID, JOIN_STATE, support_type="SIMPLIFY_STORY")) == \
        "story_help_off_topic"


def test_unsure_needs_acknowledgement():
    args = build(JOIN_ID, JOIN_STATE, support_type="UNSURE")
    assert rule("Look at the apples in the basket.", *args) == "unsure_no_acknowledgement"
    assert rule("It is okay to be unsure. Look at the apples in the basket.", *args) is None


def test_interface_help_must_be_about_controls():
    assert rule("Count the apples.", *build(JOIN_ID, JOIN_STATE, support_type="INTERFACE_HELP")) == \
        "interface_help_off_topic"


def test_learner_message_reply_rules():
    args = build(JOIN_ID, JOIN_STATE, support_type="OPEN_ENDED", message="tell me a story")
    assert rule("Once upon a time there was a fox who loved apples in the story.", *args) == "narrative_compliance"
    assert rule("That is fun to think about.", *args) == "message_reply_not_grounded"


def test_repetition_blocked():
    reply = "Move 1 more apple from the object bank into the basket."
    args = build(JOIN_ID, JOIN_STATE, history=[{"role": "tutor", "content": reply}])
    assert rule(reply, *args) == "repetition"
    assert response_is_safe(reply, *args, check_repetition=False) is True


def test_number_words_are_read():
    assert number_values("Move two apples and 3 pears") == {2, 3}
    assert number_values("Take one step at a time") == set()


def test_stated_quantity_equal_to_answer_is_quotable():
    # v4 rule: a number the story states openly may be spoken even if it equals the answer.
    question = next(q for q in QUESTION_BY_ID.values() if q["interaction"] == "EQUAL_SHARING"
                    and q["parameters"]["recipient_count"] == q["parameters"]["share_size"])
    p = question["parameters"]
    state = {"share_sizes": [0] * p["recipient_count"], "undistributed_count": p["total"]}
    args = build(question["id"], state, support_type="CHECK_WORK")
    reply = f"Look at the {p['recipient_count']} {question['visual'].get('recipient_label', 'recipient')}s. Do they all have the same share?"
    assert rule(reply, *args) != "number_not_allowed"


